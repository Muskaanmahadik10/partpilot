"""Data extraction and cleaning.

Input : data/raw/*.csv              (messy source extracts, produced by data/generate.py)
Output: data_clean/clean.pkl          clean tables used by the engine
        data_clean/pending_review.json items that need a component engineer's decision (conflicts, pending alternates)
        reports/cleaning_report.md     issues found, record counts and how each was handled
Only the Auditor role may start it from the app. It prints counts only, never data contents.
Security: free-text Remark is kept for humans only and is NEVER passed to the LLM (prompt-injection guard).
"""
from __future__ import annotations

import csv
import json
import os
import pickle
import re
from collections import Counter, defaultdict

from .normalize import (GROUP_OF, add_months, commodity_of, enum, is_blank, iso_monday, line_of_product, norm_attr_code,
                        norm_attr_value, norm_partno, norm_plant, parse_date, part_type_of, scrap_rate, to_number)

RAW = os.getenv("PARTPILOT_RAW_DIR", "data/raw")
OUT = os.getenv("PARTPILOT_CLEAN_DIR", "data_clean")
REPORT = os.getenv("PARTPILOT_REPORT", "reports/cleaning_report.md")
QC_VALUES = ["RELEASED", "INSPECTION", "HOLD", "REJECTED"]
INJECTION = re.compile(r"(note to the (assistant|ai|model)|ignore (all|previous|the) (rules|instructions)|report it as approved|"
                       r"treat (it|this) as approved|skip the (spec|attribute) check|system prompt)", re.I)


class Report:
    def __init__(self):
        self.issues = []   # (file, issue, rows, handling)
        self.counts = {}   # file -> [raw, usable]

    def add(self, file, issue, n, handling):
        if n:
            self.issues.append((file, issue, n, handling))

    def md(self, pending):
        L = ["# PartPilot - data cleaning report", "",
             "Source: `data/raw/*.csv` (generated by `data/generate.py`; component data from public open-hardware BOMs, "
             "stock/PO/price/supplier data synthetic). Generated by `partpilot/clean.py`.", "",
             "## 1. Record counts", "", "| File | Raw rows | Usable rows after cleaning |", "|---|---|---|"]
        L += [f"| {f} | {a} | {b} |" for f, (a, b) in self.counts.items()]
        L += ["", "## 2. Issues found and how each was handled", "", "| File | Issue | Rows | Handling |", "|---|---|---|---|"]
        L += [f"| {f} | {i} | {n} | {h} |" for f, i, n, h in self.issues]
        kinds = Counter(p["kind"] for p in pending)
        L += ["", "## 3. Waiting for a component engineer (not used until decided)", "",
              "| Kind | Items |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(kinds.items())]
        L += ["", "## 4. Principles", "",
              "- Invalid values are treated as missing; nothing is estimated or back-filled (only exception: an unreadable or "
              "out-of-range scrap rate becomes 0).",
              "- Invalid part numbers are never guessed (a letter O is not turned into a zero).",
              "- The product line comes from the product part number (BRD-... = dev boards, PRN-... = 3D printers).",
              "- `Remark` has no approval authority and is excluded from every LLM payload; remarks that try to instruct "
              "the assistant are listed in section 2.", ""]
        return "\n".join(L)


def read(name):
    with open(os.path.join(RAW, name), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def dedupe(rows, rep, file):
    seen, out = set(), []
    for r in rows:
        k = tuple(r.values())
        if k not in seen:
            seen.add(k)
            out.append(r)
    rep.add(file, "Exact duplicate rows", len(rows) - len(out), "kept one copy")
    return out


def run():
    rep = Report()
    pending = []

    def pend(kind, key, commodity, detail):
        pending.append({"id": f"R{len(pending) + 1:04d}", "kind": kind, "key": key, "commodity": commodity,
                        "group": GROUP_OF.get(commodity), "detail": detail})

    # ---------------- parts_master ----------------
    raw = read("parts_master.csv")
    rows = dedupe(raw, rep, "parts_master")
    by, bad = defaultdict(list), 0
    for r in rows:
        p = norm_partno(r["PartNo"])
        if p is None:
            bad += 1
            continue
        by[p].append(dict(r, PartNo=p))
    rep.add("parts_master", "Invalid part number (format, unknown commodity code)", bad, "dropped (never guessed)")
    parts, pend_parts = {}, set()
    for p, rs in by.items():
        uniq = {tuple(sorted(x.items())) for x in rs}
        if len(uniq) > 1:
            pend_parts.add(p)
            pend("PART_MASTER_CONFLICT", p, commodity_of(p), f"{len(uniq)} conflicting master records")
            continue
        parts[p] = rs[0]
    rep.add("parts_master", "Duplicates that became identical after part-number normalisation",
            sum(len(rs) - 1 for p, rs in by.items() if p not in pend_parts), "kept one copy")
    rep.add("parts_master", "Same part number with conflicting records", len(pend_parts),
            "waiting for engineer review; the part and rows that use it are not used until confirmed")
    clean_parts, cnt = {}, Counter()
    for p, r in parts.items():
        t = part_type_of(p)
        if (r["PartType"] or "").strip().upper() != t:
            cnt["type"] += 1
        line_given = (r["ProductLine"] or "").strip().upper()
        line = line_of_product(p) if t == "PRODUCT" else None
        if t == "PRODUCT" and line_given != line:
            cnt["line"] += 1
        uom = (r["UoM"] or "").strip().upper()
        if uom == "EA":
            cnt["ea"] += 1
            uom = "PCS"
        if uom not in ("PCS", "M"):
            cnt["uom"] += 1
            uom = None
        lc = enum(r["Lifecycle"], ["Active", "NRND", "EOL", "Obsolete"])
        if lc is None:
            cnt["lc"] += 1
        cost = to_number(r["UnitCostUSD"])
        if t == "COMPONENT" and (cost is None or cost <= 0):
            cnt["cost"] += 1
            cost = None
        lt = to_number(r["LeadTimeDays"])
        if lt is None or lt <= 0 or not float(lt).is_integer():
            cnt["lt"] += 1
            lt = None
        moq = to_number(r["MOQ"])
        if moq is None or moq <= 0 or not float(moq).is_integer():
            cnt["moq"] += 1
            moq = None
        clean_parts[p] = {"PartNo": p, "Description": (r["Description"] or "").strip(), "PartType": t,
                          "Commodity": commodity_of(p), "ProductLine": line, "UoM": uom, "Lifecycle": lc,
                          "MakeBuy": enum(r["MakeBuy"], ["M", "B"]), "SupplierName": (r["SupplierName"] or "").strip() or None,
                          "Manufacturer": (r["Manufacturer"] or "").strip() or None,
                          "MfrPartNo": (r["MfrPartNo"] or "").strip() or None, "LeadTimeDays": int(lt) if lt else None,
                          "MOQ": int(moq) if moq else None, "UnitCostUSD": cost}
    rep.add("parts_master", "PartType contradicts the part-number format", cnt["type"], "type taken from the part number")
    rep.add("parts_master", "Product line contradicts the product part number", cnt["line"], "line taken from the part number")
    rep.add("parts_master", "UoM 'EA'", cnt["ea"], "converted to PCS")
    rep.add("parts_master", "UoM not PCS/M/EA", cnt["uom"], "treated as missing; quantities that need a unit conversion are excluded")
    rep.add("parts_master", "Lifecycle not Active/NRND/EOL/Obsolete", cnt["lc"], "treated as missing (cannot qualify as a substitute)")
    rep.add("parts_master", "Component UnitCostUSD missing or not > 0", cnt["cost"], "treated as missing")
    rep.add("parts_master", "LeadTimeDays not a positive whole number (e.g. '6 weeks')", cnt["lt"], "treated as missing")
    rep.add("parts_master", "MOQ not a positive whole number", cnt["moq"], "treated as missing")
    rep.counts["parts_master"] = [len(raw), len(clean_parts)]
    known = set(clean_parts)

    # ---------------- part_attributes ----------------
    raw = read("part_attributes.csv")
    rows = dedupe(raw, rep, "part_attributes")
    cnt, vals = Counter(), defaultdict(list)
    for r in rows:
        p = norm_partno(r["PartNo"])
        if p is None or p not in known:
            cnt["orphan"] += 1
            continue
        c = norm_attr_code(r["AttrCode"])
        if c is None:
            cnt["code"] += 1
            continue
        if (r["AttrCode"] or "").strip() != c:
            cnt["codevar"] += 1
        v = norm_attr_value(c, r["AttrValue"], r["Unit"])
        if v is None:
            cnt["val"] += 1
            continue
        vals[(p, c)].append(v)
    attrs, nconf = defaultdict(dict), 0
    for (p, c), vs in vals.items():
        if len(set(vs)) == 1:
            attrs[p][c] = vs[0]
        else:
            nconf += 1
            pend("ATTRIBUTE_CONFLICT", f"{p}|{c}", commodity_of(p), f"{len(set(vs))} different values")
    rep.add("part_attributes", "Unknown, invalid or not-yet-approved part number", cnt["orphan"], "dropped")
    rep.add("part_attributes", "Unknown attribute code (e.g. Colour)", cnt["code"], "dropped")
    rep.add("part_attributes", "Attribute code written differently (case, underscores)", cnt["codevar"], "mapped to the standard code")
    rep.add("part_attributes", "Value not convertible to the standard unit (TBD, wrong unit)", cnt["val"], "treated as missing")
    rep.add("part_attributes", "Same part + attribute with different values after unit conversion", nconf,
            "waiting for engineer review; attribute treated as missing until confirmed")
    rep.counts["part_attributes"] = [len(raw), sum(len(v) for v in attrs.values())]

    # ---------------- bom ----------------
    raw = read("bom.csv")
    rows = dedupe(raw, rep, "bom")
    cnt, lines = Counter(), []
    for r in rows:
        par, ch = norm_partno(r["ParentPartNo"]), norm_partno(r["ChildPartNo"])
        if par is None or ch is None or par not in known or ch not in known:
            cnt["orphan"] += 1 if not (par in pend_parts or ch in pend_parts) else 0
            cnt["pendpart"] += 1 if (par in pend_parts or ch in pend_parts) else 0
            continue
        if part_type_of(par) not in ("PRODUCT", "ASSEMBLY") or part_type_of(ch) == "PRODUCT":
            cnt["type"] += 1
            continue
        q = to_number(r["QtyPer"])
        if q is None or q <= 0:
            cnt["qty"] += 1
            continue
        mu, bu = clean_parts[ch]["UoM"], (r["UoM"] or "").strip().upper()
        fac = ({"PCS": 1.0, "EA": 1.0, "KPCS": 1000.0}.get(bu) if mu == "PCS" else
               {"M": 1.0, "CM": 0.01, "MM": 0.001}.get(bu) if mu == "M" else None)
        if fac is None:
            cnt["uom"] += 1
            continue
        if bu in ("KPCS", "EA", "CM", "MM"):
            cnt["conv"] += 1
        f = parse_date(r["EffectiveFrom"])
        t = None if is_blank(r["EffectiveTo"]) else parse_date(r["EffectiveTo"])
        if f is None or (not is_blank(r["EffectiveTo"]) and t is None):
            cnt["date"] += 1
            continue
        if t is not None and t < f:
            cnt["rev"] += 1
            continue
        if not re.match(r"^\d{4}-\d{2}-\d{2}$", str(r["EffectiveFrom"]).strip()):
            cnt["datefmt"] += 1
        s, flag = scrap_rate(r["ScrapRate"])
        cnt["scrapflag"] += flag
        cnt["pct"] += "%" in (r["ScrapRate"] or "")
        lines.append({"Parent": par, "Rev": (r["BOMRev"] or "").strip(), "LineNo": str(r["LineNo"]).strip(), "Child": ch,
                      "Qty": round(q * fac, 9), "Scrap": s, "RefDes": (r["RefDes"] or "").strip(), "From": f, "To": t})
    rep.add("bom", "Parent/child part number unknown or invalid", cnt["orphan"], "line invalid, not exploded")
    rep.add("bom", "Parent/child has conflicting master records", cnt["pendpart"], "not used until an engineer confirms the part")
    rep.add("bom", "Parent is not a product/assembly, or child is a product", cnt["type"], "line invalid")
    rep.add("bom", "QtyPer not a number > 0", cnt["qty"], "line invalid")
    rep.add("bom", "BOM unit cannot be converted to the child's master unit (e.g. master PCS, BOM M)", cnt["uom"], "line invalid")
    rep.add("bom", "BOM unit converted (KPCS = 1000 PCS, EA = PCS, CM = 0.01 M, MM = 0.001 M)", cnt["conv"], "quantity converted")
    rep.add("bom", "Effective date in another accepted format (YYYY/MM/DD, YYYYMMDD)", cnt["datefmt"], "parsed")
    rep.add("bom", "Invalid effective date (only YYYY-MM-DD, YYYY/MM/DD, YYYYMMDD accepted)", cnt["date"], "line invalid")
    rep.add("bom", "EffectiveTo earlier than EffectiveFrom", cnt["rev"], "line invalid")
    rep.add("bom", "Scrap rate given as a percentage", cnt["pct"], "converted to a fraction")
    rep.add("bom", "Scrap rate unreadable or outside 0-15 %", cnt["scrapflag"], "set to 0 (the only allowed default)")
    seen, uniq = set(), []
    for ln in lines:
        k = tuple(ln.values())
        if k not in seen:
            seen.add(k)
            uniq.append(ln)
    rep.add("bom", "Duplicates that became identical after normalisation", len(lines) - len(uniq), "kept one copy")
    grp = defaultdict(list)
    for ln in uniq:
        grp[(ln["Parent"], ln["Rev"], ln["LineNo"])].append(ln)
    good, nconf = [], 0
    for k, g in grp.items():
        if len(g) > 1:
            nconf += len(g)
            kids = sorted({x["Child"] for x in g})
            pend("BOM_LINE_CONFLICT", "|".join(k), commodity_of(kids[0]), {"children": kids, "rows": len(g)})
        else:
            good.append(g[0])
    rep.add("bom", "Same parent + revision + line number with different content", nconf,
            "waiting for engineer review; not exploded until confirmed")
    edges = defaultdict(set)
    for ln in good:
        edges[ln["Parent"]].add(ln["Child"])

    def reaches(a, b):
        stack, seen_ = [a], set()
        while stack:
            n = stack.pop()
            if n == b:
                return True
            if n not in seen_:
                seen_.add(n)
                stack.extend(edges.get(n, ()))
        return False
    cyc = {(p, c) for p, cs in edges.items() for c in cs if reaches(c, p)}
    for p, c in sorted(cyc):
        pend("BOM_CYCLE", f"{p}|{c}", None, "circular reference")
    bom = [ln for ln in good if (ln["Parent"], ln["Child"]) not in cyc]
    rep.add("bom", "Lines in a circular reference", len(good) - len(bom), "waiting for engineer review; not exploded")
    rep.counts["bom"] = [len(raw), len(bom)]

    # ---------------- alternates ----------------
    raw = read("alternates.csv")
    rows = dedupe(raw, rep, "alternates")
    cnt, alts = Counter(), []
    for r in rows:
        a, b = norm_partno(r["PrimaryPartNo"]), norm_partno(r["AltPartNo"])
        if a in pend_parts or b in pend_parts:
            cnt["pendpart"] += 1
            continue
        if a is None or b is None or a not in known or b not in known:
            cnt["orphan"] += 1
            continue
        sid = (r["SubID"] or "").strip().upper()
        scope = enum(r["Scope"], ["GLOBAL", "LINE", "ASSEMBLY"])
        sv_raw, sv, okscope = r["ScopeValue"], None, True
        if scope == "GLOBAL":
            okscope = is_blank(sv_raw)
        elif scope == "LINE":
            sv = (sv_raw or "").strip().upper()
            okscope = sv in ("BRD", "PRN")
        elif scope == "ASSEMBLY":
            sv = norm_partno(sv_raw)
            okscope = sv is not None and sv in known and part_type_of(sv) in ("PRODUCT", "ASSEMBLY")
        else:
            okscope = False
        ratio, prio = to_number(r["QtyRatio"]), to_number(r["Priority"])
        vf = parse_date(r["ValidFrom"])
        vt = None if is_blank(r["ValidTo"]) else parse_date(r["ValidTo"])
        set_id = None if is_blank(r["SetID"]) else (r["SetID"] or "").strip().upper()
        invalid = (a == b or part_type_of(a) != "COMPONENT" or part_type_of(b) != "COMPONENT" or not okscope or ratio is None
                   or ratio <= 0 or vf is None or (not is_blank(r["ValidTo"]) and vt is None) or (vt is not None and vt < vf)
                   or not re.match(r"^SUB-\d{4}$", sid) or (set_id is not None and not re.match(r"^SET-\d{2}$", set_id)))
        if invalid:
            cnt["invalid"] += 1
            continue
        st = enum(r["Status"], ["Approved", "Pending", "Rejected"])
        if st is None:
            cnt["status"] += 1
        two_way = enum(r["TwoWay"], ["Y", "N"]) or "N"
        mix = enum(r["MixAllowed"], ["Y", "N"]) or "N"
        alts.append({"SubID": sid, "Primary": a, "Alt": b, "Scope": scope, "ScopeValue": sv,
                     "Priority": int(prio) if prio is not None else 999, "QtyRatio": ratio, "TwoWay": two_way,
                     "MixAllowed": mix, "SetID": set_id, "Status": st, "ValidFrom": vf, "ValidTo": vt,
                     "Remark_HUMAN_ONLY": (r["Remark"] or "").strip()})
    rep.add("alternates", "Primary/substitute has conflicting master records", cnt["pendpart"], "not used until confirmed")
    rep.add("alternates", "Primary/substitute part number unknown or invalid", cnt["orphan"], "record invalid")
    rep.add("alternates", "Invalid record: same part, not a component, bad scope, ratio <= 0, invalid or reversed dates, "
            "bad SubID/SetID", cnt["invalid"], "record invalid")
    rep.add("alternates", "Status not Approved/Pending/Rejected (e.g. 'approved?')", cnt["status"], "treated as missing -> not usable")
    grp = defaultdict(list)
    for x in alts:
        grp[(x["Primary"], x["Alt"], x["Scope"], x["ScopeValue"])].append(x)
    alt_ok, nconf = [], 0
    for k, g in grp.items():
        contents = {tuple((kk, str(vv)) for kk, vv in x.items() if kk != "SubID") for x in g}
        if len(contents) > 1:
            nconf += len(g)
            pend("ALTERNATE_CONFLICT", "|".join(map(str, k)), commodity_of(k[0]), {"records": [x["SubID"] for x in g]})
        else:
            alt_ok.append(g[0])
    rep.add("alternates", "Same primary + substitute + scope with conflicting records", nconf, "waiting for engineer review; not used")
    npend = 0
    for x in alt_ok:
        if x["Status"] == "Pending":
            npend += 1
            pend("ALTERNATE_PENDING", x["SubID"], commodity_of(x["Primary"]),
                 {"primary": x["Primary"], "substitute": x["Alt"], "scope": x["Scope"], "scope_value": x["ScopeValue"]})
    rep.add("alternates", "Status = Pending", npend,
            "usable only after the engineer responsible for the PRIMARY part's commodity approves; Remark has no authority")
    inj = [x["SubID"] for x in alt_ok if INJECTION.search(x["Remark_HUMAN_ONLY"])]
    rep.add("alternates", "Remark that tries to instruct the assistant (claims approval / asks to skip checks): "
            + (", ".join(inj) or "none"), len(inj), "ignored; Remark never reaches the LLM; the record keeps its structured status")
    rep.counts["alternates"] = [len(raw), len(alt_ok)]

    # ---------------- inventory ----------------
    raw = read("inventory.csv")
    rows = dedupe(raw, rep, "inventory")
    cnt, lots = Counter(), []
    for r in rows:
        p, pl = norm_partno(r["PartNo"]), norm_plant(r["Plant"])
        if p is None or p not in known:
            cnt["orphan"] += 1
            continue
        if pl is None:
            cnt["plant"] += 1
            continue
        if (r["Plant"] or "").strip() != pl:
            cnt["alias"] += 1
        oh = to_number(r["QtyOnHand"])
        al = 0.0 if is_blank(r["QtyAllocated"]) else to_number(r["QtyAllocated"])
        if oh is None or oh < 0:
            cnt["oh"] += 1
            continue
        if al is None or al < 0 or al > oh:
            cnt["al"] += 1
            continue
        mu, iu = clean_parts[p]["UoM"], (r["UoM"] or "").strip().upper()
        fac = {"PCS": 1, "EA": 1, "KPCS": 1000}.get(iu) if mu == "PCS" else ({"M": 1}.get(iu) if mu == "M" else None)
        if fac is None:
            cnt["uom"] += 1
            continue
        if iu == "KPCS":
            cnt["kpcs"] += 1
        qc = enum(r["QCStatus"], QC_VALUES)
        if qc is None:
            cnt["qc"] += 1
        shelf = attrs.get(p, {}).get("ShelfLifeMonths")
        mfg = iso_monday(r["DateCode"])
        exp = add_months(mfg, int(shelf)) if (shelf and mfg) else None
        lots.append({"Plant": pl, "PartNo": p, "LotNo": (r["LotNo"] or "").strip(), "DateCode": (r["DateCode"] or "").strip(),
                     "QC": qc, "Avail": (oh - al) * fac, "Shelf": shelf, "Mfg": mfg, "Expiry": exp})
    rep.add("inventory", "Unknown or invalid part number", cnt["orphan"], "lot excluded")
    rep.add("inventory", "Unknown plant code (e.g. HQ)", cnt["plant"], "lot excluded")
    rep.add("inventory", "Plant written as an alias (North Ridge, PLANT NRG, bay-haven, ...)", cnt["alias"], "mapped to the plant code")
    rep.add("inventory", "QtyOnHand negative or not a number", cnt["oh"], "lot excluded")
    rep.add("inventory", "QtyAllocated invalid or greater than QtyOnHand", cnt["al"], "lot excluded")
    rep.add("inventory", "Unit inconsistent with the master unit (e.g. CM for a part kept in M)", cnt["uom"], "lot excluded")
    rep.add("inventory", "Lots counted in KPCS", cnt["kpcs"], "x1000 to PCS")
    rep.add("inventory", "QCStatus not RELEASED/INSPECTION/HOLD/REJECTED (e.g. ok, passed)", cnt["qc"], "treated as missing -> not available")
    rep.add("inventory", "QCStatus INSPECTION/HOLD/REJECTED", sum(1 for x in lots if x["QC"] in ("INSPECTION", "HOLD", "REJECTED")),
            "kept, never counted as available")
    rep.add("inventory", "Shelf-life part with an invalid date code (incl. a week that does not exist)",
            sum(1 for x in lots if x["Shelf"] and x["Mfg"] is None), "lot not usable (expiry cannot be confirmed)")
    rep.counts["inventory"] = [len(raw), len(lots)]

    # ---------------- open_po ----------------
    raw = read("open_po.csv")
    rows = dedupe(raw, rep, "open_po")
    cnt, pos = Counter(), []
    for r in rows:
        p, pl = norm_partno(r["PartNo"]), norm_plant(r["Plant"])
        if p is None or p not in known:
            cnt["orphan"] += 1
            continue
        if pl is None:
            cnt["plant"] += 1
            continue
        st = enum(r["Status"], ["Open", "Closed", "Cancelled"])
        if st is None:
            cnt["st"] += 1
            continue
        o = to_number(r["OrderQty"])
        rc = 0.0 if is_blank(r["ReceivedQty"]) else to_number(r["ReceivedQty"])
        if o is None or rc is None or o <= 0 or rc < 0 or rc > o:
            cnt["qty"] += 1
            continue
        pu = (r["UoM"] or "").strip().upper().replace("EA", "PCS")
        if pu != clean_parts[p]["UoM"]:
            cnt["uom"] += 1
            continue
        od, eta = parse_date(r["OrderDate"]), parse_date(r["ETA"])
        if eta is None:
            cnt["eta"] += 1
            continue
        if od is not None and eta < od:
            cnt["etaod"] += 1
            continue
        price = to_number(r["UnitPriceUSD"])
        pos.append({"PONo": (r["PONo"] or "").strip(), "POLine": str(r["POLine"]).strip(), "Plant": pl, "PartNo": p,
                    "SupplierName": (r["Supplier"] or "").strip() or None, "OpenQty": o - rc, "Status": st,
                    "UnitPriceUSD": price if (price and price > 0) else None, "OrderDate": od, "ETA": eta})
    rep.add("open_po", "Unknown or invalid part number", cnt["orphan"], "line excluded")
    rep.add("open_po", "Unknown plant code", cnt["plant"], "line excluded")
    rep.add("open_po", "Status not Open/Closed/Cancelled (e.g. 'Open?')", cnt["st"], "line excluded")
    rep.add("open_po", "OrderQty/ReceivedQty invalid or received > ordered", cnt["qty"], "line excluded")
    rep.add("open_po", "Unit inconsistent with the master unit (e.g. BOX)", cnt["uom"], "line excluded")
    rep.add("open_po", "ETA unreadable (e.g. TBD)", cnt["eta"], "not counted as in transit")
    rep.add("open_po", "ETA earlier than the order date", cnt["etaod"], "line excluded")
    rep.add("open_po", "Closed/Cancelled lines", sum(1 for x in pos if x["Status"] != "Open"), "never counted as in transit")
    rep.counts["open_po"] = [len(raw), len(pos)]

    os.makedirs(OUT, exist_ok=True)
    if os.path.dirname(REPORT):
        os.makedirs(os.path.dirname(REPORT), exist_ok=True)
    with open(os.path.join(OUT, "clean.pkl"), "wb") as f:
        pickle.dump({"parts": clean_parts, "attrs": dict(attrs), "bom": bom, "alternates": alt_ok, "inventory": lots, "po": pos,
                     "pending": pending}, f)
    with open(os.path.join(OUT, "pending_review.json"), "w", encoding="utf-8") as f:
        json.dump(pending, f, ensure_ascii=False, indent=1, default=str)
    with open(REPORT, "w", encoding="utf-8") as f:
        f.write(rep.md(pending))
    return {"counts": rep.counts, "pending": len(pending), "report": REPORT}


